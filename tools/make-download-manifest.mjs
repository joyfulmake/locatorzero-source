// Writes web/downloads/manifest.js for the download page. A script, not JSON, because the site's CSP allows no
// fetch at all, not even to itself.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'web/downloads');
const version = JSON.parse(fs.readFileSync(path.join(root, 'desktop/src-tauri/tauri.conf.json'), 'utf8')).version;
const [run, sha] = process.argv.slice(2);

const kinds = [
  [/x64-setup\.exe$/, 'windows', 'exe', 'Windows installer', 'Recommended for most people'],
  [/\.msi$/, 'windows', 'msi', 'Windows MSI package', 'For IT teams deploying to many PCs'],
  [/aarch64\.dmg$/, 'mac', 'arm', 'Mac with Apple silicon', 'M1, M2, M3, M4 and later'],
  [/x64\.dmg$/, 'mac', 'intel', 'Mac with Intel processor', 'Macs from before late 2020'],
  [/\.deb$/, 'linux', 'deb', 'Debian, Ubuntu, Mint, Kali', '.deb package'],
  [/\.rpm$/, 'linux', 'rpm', 'Fedora, openSUSE, RHEL', '.rpm package'],
];
const files = fs.readdirSync(dir).filter(f => !/^(SHA256SUMS\.txt(\.asc)?|manifest\.js)$/.test(f)).map(f => {
  const buf = fs.readFileSync(path.join(dir, f));
  const k = kinds.find(([re]) => re.test(f)) || [null, 'other', 'other', f, ''];
  return { file: f, os: k[1], id: k[2], title: k[3], note: k[4], bytes: buf.length, sha256: crypto.createHash('sha256').update(buf).digest('hex') };
}).sort((a, b) => kinds.findIndex(k => k[2] === a.id) - kinds.findIndex(k => k[2] === b.id));
const manifest = { version, built: new Date().toISOString().slice(0, 10), run: run || null, commit: (sha || '').slice(0, 7), files };
fs.writeFileSync(path.join(dir, 'manifest.js'),
  '// Generated by tools/make-download-manifest.mjs. Do not edit.\nwindow.LZ_DOWNLOADS = ' + JSON.stringify(manifest, null, 2) + ';\n');
console.log('manifest: ' + files.length + ' files, version ' + version);
